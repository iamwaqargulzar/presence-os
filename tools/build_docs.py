#!/usr/bin/env python3
"""Rebuild the compiled files of the Presence OS specification package.

Run from anywhere:  python3 tools/build_docs.py

Rebuilds docs/MASTER_SPEC.md, docs/COMPLETE_CONTEXT_EXPORT.md and docs/INDEX.md,
then checks relative Markdown links. Git history is the integrity record.
Uses only the Python standard library. Exits non-zero if a link is broken.
"""
import datetime
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
TODAY = datetime.date.today().isoformat()
GENERATED = {"docs/MASTER_SPEC.md", "docs/COMPLETE_CONTEXT_EXPORT.md", "docs/INDEX.md"}
SKIP_DIRS = {".git", "node_modules", "__pycache__", ".venv"}


def files():
    out = []
    for p in ROOT.rglob("*"):
        if p.is_file() and not (set(p.relative_to(ROOT).parts) & SKIP_DIRS):
            out.append(p.relative_to(ROOT).as_posix())
    return sorted(out)


def title(rel):
    for line in (ROOT / rel).read_text().splitlines():
        if line.startswith("# "):
            return line[2:].strip()
    return rel


def master_sources():
    """Keep the existing order of the master spec; drop files that no longer exist."""
    ms = ROOT / "docs/MASTER_SPEC.md"
    order = re.findall(r"<!-- Source: (\S+) -->", ms.read_text()) if ms.exists() else []
    order = [s for s in order if (ROOT / s).exists() and "/archive/" not in s]
    for extra in ("docs/delivery/gates.md",):
        if extra not in order and (ROOT / extra).exists():
            order.append(extra)
    return order


def build_master():
    parts = [
        "# Presence OS — Master Product & Engineering Specification\n",
        f"> Compiled on {TODAY} by `tools/build_docs.py` from the focused documents. Do not edit this file by hand.",
        "> Presence OS is run by one operator for their own companies and managed clients; it is not sold (ADR-0030).",
        "> Accepted ADRs and task contracts in `specs/` control where they differ from this compiled copy.\n",
        "For implementation, start at `../00_START_HERE.md` and `../specs/R0/README.md`.\n",
    ]
    for src in master_sources():
        parts.append(f"\n---\n\n<!-- Source: {src} -->\n\n{(ROOT / src).read_text().strip()}\n")
    (ROOT / "docs/MASTER_SPEC.md").write_text("\n".join(parts))


def build_export(all_files):
    parts = [
        "# COMPLETE CONTEXT EXPORT — Presence OS Specification Package\n",
        f"Generated: {TODAY} by `tools/build_docs.py`. This disaster-recovery file concatenates the current Markdown sources. "
        "Original file paths remain the authoritative organization. Archived files are not included.\n",
    ]
    for rel in all_files:
        if rel.endswith(".md") and rel not in GENERATED and not rel.startswith("docs/archive/"):
            parts.append(f"\n---\n\n# FILE: `{rel}`\n\n{(ROOT / rel).read_text().strip()}\n")
    (ROOT / "docs/COMPLETE_CONTEXT_EXPORT.md").write_text("\n".join(parts))


def build_index(all_files):
    docs = [f for f in all_files if f.startswith("docs/") and f.endswith(".md") and f != "docs/INDEX.md"]
    groups = {}
    for f in docs:
        rest = f[len("docs/"):]
        key = rest.split("/")[0] if "/" in rest else rest
        groups.setdefault(key, []).append(f)
    lines = ["# Documentation Index\n", f"Generated {TODAY} by `tools/build_docs.py`. Files under `archive` are not current.\n"]
    for key in sorted(groups, key=lambda k: ("/" in groups[k][0][5:], k)):
        lines.append(f"## {key}")
        for f in groups[key]:
            lines.append(f"- [`{f}`](../{f}) — {title(f)}")
        lines.append("")
    (ROOT / "docs/INDEX.md").write_text("\n".join(lines))


def check_links(all_files):
    broken = []
    for rel in all_files:
        if not rel.endswith(".md") or rel in ("docs/MASTER_SPEC.md", "docs/COMPLETE_CONTEXT_EXPORT.md") or rel.startswith("docs/archive/"):
            continue
        base = (ROOT / rel).parent
        for target in re.findall(r"\]\(([^)\s]+)\)", (ROOT / rel).read_text()):
            if re.match(r"[a-z]+:", target) or target.startswith("#"):
                continue
            path = target.split("#")[0]
            if path and not (base / path).exists():
                broken.append(f"{rel}: {target}")
    return broken


def main():
    build_master()
    build_index(files())
    build_export(files())
    broken = check_links(files())
    print(f"files: {len(files())}")
    if broken:
        print("BROKEN LINKS:")
        print("\n".join(broken))
        sys.exit(1)
    print("links: ok")


if __name__ == "__main__":
    main()
